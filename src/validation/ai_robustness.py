# ============================================================
# AURORA
# Phase 16-C
#
# Frozen AI / FDIR robustness evaluation
#
#
# Purpose:
#
# Evaluate the Phase-15 temporal anomaly detector WITHOUT:
#
#   - retraining
#   - recalibration
#   - threshold adaptation
#
# under the varying GNSS/fault conditions generated by
# the validated Phase-16 Latin-Hypercube campaign.
#
#
# Two paired sequences are created for every scenario:
#
#       NOMINAL
#       FAULT
#
# They share:
#
#       same orbit
#       same geometry
#       same pseudorange noise
#       same prior
#
# The only difference is fault injection.
#
#
# AI prior model:
#
# Phase 16-C keeps the Phase-15 navigation-prior model:
#
#       position prior error ~ N(0, 20 m)
#       clock prior error ~ N(0, 10 m)
#
# This phase therefore tests robustness to:
#
#       pseudorange noise
#       fault magnitude
#       fault timing
#       fault duration
#       small truth-trajectory changes caused by a_ng
#
# Full navigation-state uncertainty was tested in 016-B.
# ============================================================


