# 6. BUILD PAIRED NOMINAL / FAULT SEQUENCES
# ------------------------------------------------------------

def _generate_paired_sequences(
    scenario
):

    scenario = dict(
        scenario
    )


    truth = (
        _build_truth(
            base_acceleration=
                scenario[
                    "non_gravitational_acceleration_mps2"
                ]
        )
    )


    pseudorange_rng = np.random.default_rng(
        int(
            scenario[
                "scenario_seed"
            ]
        )
        +
        5101
    )


    prior_rng = np.random.default_rng(
        int(
            scenario[
                "scenario_seed"
            ]
        )
        +
        5202
    )


    # ========================================================
    # Keep Phase-15 prior model fixed.
    # ========================================================

    prior_position_error = (
        prior_rng.normal(
            0.0,
            PRIOR_POSITION_SIGMA_M,
            size=3
        )
    )


    prior_clock_error = float(
        prior_rng.normal(
            0.0,
            PRIOR_CLOCK_SIGMA_M
        )
    )


    pseudorange_noise_std = float(
        scenario[
            "pseudorange_noise_std_m"
        ]
    )


    fault_magnitude = float(
        scenario[
            "fault_magnitude_m"
        ]
    )


    fault_start_min = float(
        scenario[
            "fault_start_min"
        ]
    )


    fault_end_min = (
        fault_start_min
        +
        float(
            scenario[
                "fault_duration_min"
            ]
        )
    )


    rows = []


    failed_epochs = (
        0
    )


    expected_epoch_count = len(
        truth[
            "sequence_indices"
        ]
    )


    for epoch_index in truth[
        "sequence_indices"
    ]:

        reception_time_seconds = float(
            truth[
                "time"
            ][
                epoch_index
            ]
        )


        reception_time_minutes = float(
            truth[
                "time_minutes"
            ][
                epoch_index
            ]
        )


        true_receiver_position = (
            truth[
                "truth_states"
            ][
                epoch_index,
                0:3
            ]
        )


        prior_position = (
            true_receiver_position
            +
            prior_position_error
        )


        prior_clock_bias_meters = (
            TRUE_CLOCK_BIAS_METERS
            +
            prior_clock_error
        )


        # ====================================================
        # GNSS visibility
        # ====================================================

        (
            all_positions,
            all_ids
        ) = generate_simplified_gps_positions(
            time_seconds=
                reception_time_seconds
        )


        (
            _,
            visible_ids
        ) = select_visible_gnss_satellites(
            receiver_position=
                true_receiver_position,

            satellite_positions=
                all_positions,

            satellite_ids=
                all_ids
        )


        working_ids = (
            _select_five_satellites(
                visible_ids
            )
        )


        if working_ids is None:

            failed_epochs += (
                1
            )

            continue


        # ====================================================
        # ONE noise realization shared by paired conditions.
        # ====================================================

        nominal_measurement = (
            simulate_pseudoranges_with_transmit_time(
                receiver_position=
                    true_receiver_position,

                satellite_ids=
                    working_ids,

                reception_time_seconds=
                    reception_time_seconds,

                receiver_clock_bias_seconds=
                    RECEIVER_CLOCK_BIAS_SECONDS,

                pseudorange_noise_std=
                    pseudorange_noise_std,

                rng=
                    pseudorange_rng
            )
        )


        base_pseudoranges = np.asarray(
            nominal_measurement[
                "pseudoranges"
            ],
            dtype=float
        )


        fault_target = (
            _choose_fault_target(
                working_ids
            )
        )


        fault_target_index = (
            working_ids.index(
                fault_target
            )
        )


        fault_active = (
            reception_time_minutes
            >=
            fault_start_min
            and
            reception_time_minutes
            <
            fault_end_min
        )


        # ====================================================
        # NOMINAL + FAULT conditions
        # ====================================================

        epoch_success = (
            True
        )


        for condition in [
            "NOMINAL",
            "FAULT"
        ]:

            pseudoranges = (
                base_pseudoranges.copy()
            )


            injected_fault = (
                condition
                ==
                "FAULT"
                and
                fault_active
            )


            if injected_fault:

                pseudoranges[
                    fault_target_index
                ] += (
                    fault_magnitude
                )


            row = (
                _build_fdir_feature_row(
                    satellite_ids=
                        working_ids,

                    pseudoranges=
                        pseudoranges,

                    reception_time_seconds=
                        reception_time_seconds,

                    prior_position=
                        prior_position,

                    prior_clock_bias_meters=
                        prior_clock_bias_meters,

                    pseudorange_noise_std=
                        pseudorange_noise_std
                )
            )


            if row is None:

                epoch_success = (
                    False
                )

                break


            rows.append(
                {
                    "scenario_id":
                        str(
                            scenario[
                                "scenario_id"
                            ]
                        ),

                    "condition":
                        condition,

                    "epoch_index":
                        int(
                            epoch_index
                        ),

                    "time_seconds":
                        reception_time_seconds,

                    "time_minutes":
                        reception_time_minutes,

                    "fault_active":
                        int(
                            injected_fault
                        ),

                    "fault_magnitude_m":
                        fault_magnitude,

                    "pseudorange_noise_std_m":
                        pseudorange_noise_std,

                    **row
                }
            )


        if not epoch_success:

            # Remove a possible first paired row from this epoch.
            rows = [
                row
                for row in rows
                if row[
                    "epoch_index"
                ]
                !=
                int(
                    epoch_index
                )
            ]


            failed_epochs += (
                1
            )


    dataframe = pd.DataFrame(
        rows
    )


    if len(
        dataframe
    ) == 0:

        raise RuntimeError(
            "Empty Phase-16C scenario dataset."
        )


    expected_rows = (
        2
        *
        (
            expected_epoch_count
            -
            failed_epochs
        )
    )


    pairs_complete = (
        len(
            dataframe
        )
        ==
        expected_rows
    )


    return {
        "dataframe":
            dataframe,

        "failed_epochs":
            int(
                failed_epochs
            ),

        "expected_epoch_count":
            int(
                expected_epoch_count
            ),

        "pairs_complete":
            bool(
                pairs_complete
            ),

        "synchronization_error":
            float(
                truth[
                    "synchronization_error"
                ]
            ),

        "fault_start_min":
            fault_start_min,

        "fault_end_min":
            fault_end_min
    }


