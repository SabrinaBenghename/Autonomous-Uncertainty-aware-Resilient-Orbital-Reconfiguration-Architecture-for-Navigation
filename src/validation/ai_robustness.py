# 7. ADD AI + SUPERVISOR
# ------------------------------------------------------------

def _run_frozen_detector(
    dataframe,
    detector
):

    dataframe = (
        add_causal_temporal_features(
            dataframe=
                dataframe,

            group_columns=[
                "scenario_id",
                "condition"
            ],

            time_column=
                "time_seconds"
        )
    )


    valid_mask = (
        temporal_feature_valid_mask(
            dataframe
        )
    )


    dataframe[
        "temporal_features_valid"
    ] = (
        valid_mask.astype(
            int
        )
    )


    valid_dataframe = dataframe[
        valid_mask
    ].copy()


    if len(
        valid_dataframe
    ) == 0:

        raise RuntimeError(
            "No valid temporal features in Phase 16-C scenario."
        )


    valid_dataframe = (
        valid_dataframe.sort_values(
            [
                "condition",
                "time_seconds"
            ]
        )
        .reset_index(
            drop=True
        )
    )


    valid_dataframe[
        "temporal_score"
    ] = (
        detector.score_samples(
            valid_dataframe
        )
    )


    valid_dataframe[
        "ai_raw_alarm"
    ] = (
        valid_dataframe[
            "temporal_score"
        ]
        >=
        detector.threshold
    ).astype(
        int
    )


    naive_or_alarm = np.zeros(
        len(
            valid_dataframe
        ),
        dtype=int
    )


    hybrid_alarm = np.zeros(
        len(
            valid_dataframe
        ),
        dtype=int
    )


    ai_confirmed = np.zeros(
        len(
            valid_dataframe
        ),
        dtype=int
    )


    for condition in [
        "NOMINAL",
        "FAULT"
    ]:

        indices = (
            valid_dataframe.index[
                valid_dataframe[
                    "condition"
                ]
                ==
                condition
            ]
            .tolist()
        )


        indices = sorted(
            indices,
            key=
                lambda index:
                    valid_dataframe.loc[
                        index,
                        "time_seconds"
                    ]
        )


        supervisor = (
            HybridGnssAnomalySupervisor(
                ai_vote_window=
                    AI_VOTE_WINDOW,

                minimum_ai_votes=
                    MINIMUM_AI_VOTES
            )
        )


        for index in indices:

            classical_alarm = bool(
                valid_dataframe.loc[
                    index,
                    "fdir_detected"
                ]
            )


            raw_ai_alarm = bool(
                valid_dataframe.loc[
                    index,
                    "ai_raw_alarm"
                ]
            )


            decision = (
                supervisor.update(
                    classical_alarm=
                        classical_alarm,

                    ai_raw_alarm=
                        raw_ai_alarm
                )
            )


            naive_or_alarm[
                index
            ] = int(
                classical_alarm
                or
                raw_ai_alarm
            )


            hybrid_alarm[
                index
            ] = int(
                decision.hard_alarm
            )


            ai_confirmed[
                index
            ] = int(
                decision.ai_confirmed
            )


    valid_dataframe[
        "naive_or_alarm"
    ] = (
        naive_or_alarm
    )


    valid_dataframe[
        "hybrid_alarm"
    ] = (
        hybrid_alarm
    )


    valid_dataframe[
        "ai_confirmed"
    ] = (
        ai_confirmed
    )


    return valid_dataframe


