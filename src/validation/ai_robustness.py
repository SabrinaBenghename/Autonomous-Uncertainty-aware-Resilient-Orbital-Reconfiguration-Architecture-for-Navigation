def _percentage(
    values
):

    values = np.asarray(
        values,
        dtype=bool
    )


    if values.size == 0:

        return np.nan


    return float(
        100.0
        *
        np.mean(
            values
        )
    )


def _select_five_satellites(
    visible_ids
):

    visible_ids = [
        str(
            satellite_id
        ).strip()
        for satellite_id in visible_ids
    ]


    if len(
        visible_ids
    ) < 5:

        return None


    if (
        PREFERRED_FAULT_SATELLITE
        in
        visible_ids
    ):

        other_ids = [
            satellite_id
            for satellite_id in visible_ids
            if satellite_id
            !=
            PREFERRED_FAULT_SATELLITE
        ]


        return (
            [
                PREFERRED_FAULT_SATELLITE
            ]
            +
            other_ids[
                :4
            ]
        )


    return (
        visible_ids[
            :5
        ]
    )


def _choose_fault_target(
    satellite_ids
):

    if (
        PREFERRED_FAULT_SATELLITE
        in
        satellite_ids
    ):

        return (
            PREFERRED_FAULT_SATELLITE
        )


    return (
        satellite_ids[
            0
        ]
    )


# ------------------------------------------------------------
# 4. TRUTH
# ------------------------------------------------------------

def _build_truth(
    base_acceleration
):

    simulation_duration_seconds = (
        SIMULATION_END_MIN
        *
        60.0
    )


    number_of_epochs = (
        int(
            simulation_duration_seconds
            /
            DT
        )
        +
        1
    )


    time = np.linspace(
        0.0,
        simulation_duration_seconds,
        number_of_epochs
    )


    time_minutes = (
        time
        /
        60.0
    )


    (
        initial_position,
        initial_velocity
    ) = keplerian_to_cartesian(
        SEMI_MAJOR_AXIS,
        ECCENTRICITY,
        INCLINATION,
        RAAN,
        ARGUMENT_OF_PERIAPSIS,
        TRUE_ANOMALY
    )


    initial_state = np.concatenate(
        (
            initial_position,
            initial_velocity
        )
    )


    solution = (
        propagate_orbit_with_j2_and_drag_like(
            initial_state=
                initial_state,

            duration=
                simulation_duration_seconds,

            number_of_points=
                number_of_epochs,

            base_acceleration=
                float(
                    base_acceleration
                )
        )
    )


    truth_states = (
        solution.y.T
    )


    synchronization_error = float(
        np.max(
            np.abs(
                solution.t
                -
                time
            )
        )
    )


    sequence_mask = (
        (
            time_minutes
            >=
            SEQUENCE_START_MIN
        )
        &
        (
            time_minutes
            <=
            SEQUENCE_END_MIN
        )
    )


    sequence_indices = np.where(
        sequence_mask
    )[0]


    return {
        "time":
            time,

        "time_minutes":
            time_minutes,

        "truth_states":
            truth_states,

        "sequence_indices":
            sequence_indices,

        "synchronization_error":
            synchronization_error
    }


# ------------------------------------------------------------
# 5. BUILD ONE FDIR FEATURE ROW
# ------------------------------------------------------------

def _build_fdir_feature_row(
    satellite_ids,
    pseudoranges,
    reception_time_seconds,
    prior_position,
    prior_clock_bias_meters,
    pseudorange_noise_std
):

    try:

        fdir_result = (
            solve_gnss_with_fdir_transmit_time(
                satellite_ids=
                    satellite_ids,

                pseudoranges=
                    pseudoranges,

                reception_time_seconds=
                    reception_time_seconds,

                initial_position=
                    prior_position,

                initial_clock_bias_meters=
                    prior_clock_bias_meters,

                pseudorange_noise_std=
                    pseudorange_noise_std,

                confidence=
                    GNSS_CONFIDENCE
            )
        )


    except (
        RuntimeError,
        ValueError,
        np.linalg.LinAlgError
    ):

        return None


    full_solution = (
        fdir_result.get(
            "full_solution",
            None
        )
    )


    if full_solution is None:

        full_solution = (
            fdir_result.get(
                "solution",
                None
            )
        )


    if (
        full_solution is None
        or
        not full_solution.get(
            "converged",
            False
        )
    ):

        return None


    try:

        covariance_result = (
            compute_transmit_time_solution_covariance(
                receiver_position=
                    full_solution[
                        "position"
                    ],

                satellite_ids=
                    satellite_ids,

                reception_time_seconds=
                    reception_time_seconds,

                pseudorange_noise_std=
                    pseudorange_noise_std
            )
        )


        pdop = float(
            covariance_result[
                "pdop"
            ]
        )


    except (
        RuntimeError,
        ValueError,
        np.linalg.LinAlgError,
        KeyError
    ):

        return None


    features = (
        extract_gnss_anomaly_features(
            fdir_result=
                fdir_result,

            number_of_satellites=
                len(
                    satellite_ids
                ),

            pseudorange_noise_std=
                pseudorange_noise_std,

            confidence=
                GNSS_CONFIDENCE,

            pdop=
                pdop,

            prior_position=
                prior_position,

            prior_clock_bias_meters=
                prior_clock_bias_meters
        )
    )


    if features is None:

        return None


    return {
        "fdir_detected":
            int(
                bool(
                    fdir_result.get(
                        "fault_detected",
                        False
                    )
                )
            ),

        "measurement_accepted":
            int(
                bool(
                    fdir_result.get(
                        "measurement_accepted",
                        False
                    )
                )
            ),

        **features
    }


